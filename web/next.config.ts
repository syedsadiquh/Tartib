import type { NextConfig } from "next";

/**
 * The browser talks to this app only; `/api/*` is proxied to the FastAPI
 * service (ARCH §1, D-02) so the app stays same-origin and needs no CORS.
 */
const API_ORIGIN = process.env.API_ORIGIN ?? "http://localhost:8000";
const isDev = process.env.NODE_ENV !== "production";

/**
 * CSP is assembled from parts so dev-only allowances (`unsafe-eval` for the
 * React refresh runtime, websockets for HMR) never reach a production build.
 * `frame-ancestors 'none'` is the frame guard; X-Frame-Options is kept for
 * older browsers.
 */
const contentSecurityPolicy = [
  "default-src 'self'",
  `script-src 'self' 'unsafe-inline'${isDev ? " 'unsafe-eval'" : ""}`,
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "font-src 'self' data:",
  `connect-src 'self'${isDev ? " ws: wss:" : ""}`,
  "frame-ancestors 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "object-src 'none'",
].join("; ");

const securityHeaders = [
  { key: "Content-Security-Policy", value: contentSecurityPolicy },
  { key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains; preload" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
];

const nextConfig: NextConfig = {
  typedRoutes: true,
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
  async rewrites() {
    return [{ source: "/api/:path*", destination: `${API_ORIGIN}/api/:path*` }];
  },
  async headers() {
    return [{ source: "/:path*", headers: securityHeaders }];
  },
};

export default nextConfig;
